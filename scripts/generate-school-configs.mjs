/**
 * Pragnya Mitra — generate per-school dedicated worker configs for Enterprise schools.
 *
 * Reads schools.json and generates a wrangler-<slug>.toml for each dedicated school.
 * The config is meant for:
 *
 *   wrangler deploy -c wrangler-<slug>.toml
 *
 * Each config carries its own [[routes]] entry (slug.pragnya.nasven.com/*) so the
 * dedicated worker serves that school directly. Static assets are auto-served from
 * [assets], exactly like the shared worker.
 */
import fs from 'fs';
import path from 'path';
import { internalApiFetch, platformBaseUrl } from './lib/internal-auth.mjs';

const REGISTRY_FILE = 'schools.json';

// Must stay identical to isSlugValid() in api/lib/provisioning.ts.
const SLUG_RE = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/;

// Public vars kept in sync with the shared worker (wrangler.toml).
const PLATFORM_VARS = {
  ENVIRONMENT: 'production',
  WEB_PUSH_VAPID_PUBLIC_KEY:
    'BJlcKjZBfC5YzmoIxZ1ndHRJAiemr7Rdi4LBuceK6GI7N6g9aV3ctHpKCtZ8RbaPugnfvfJQNBiRTi63CGipHP4',
  WEB_PUSH_VAPID_SUBJECT: 'mailto:pragnya@navasanganakah.com',
  SCHOOL_NAME: 'Pragnya Mitra Public School',
};

async function fetchMainDbRegistry() {
  try {
    const result = await internalApiFetch(process.env, '/api/internal/provisioning/registry');
    if (result && result.success && Array.isArray(result.schools)) {
      const map = new Map();
      for (const s of result.schools) {
        if (s && s.schoolId) map.set(s.schoolId, s);
      }
      return map;
    }
  } catch (e) {
    console.warn('⚠️ Could not fetch provisioning registry from main DB (' + platformBaseUrl() + '):', e.message);
    console.warn('   Falling back to schools.json only.');
  }
  return null;
}

async function main() {
  if (!fs.existsSync(REGISTRY_FILE)) {
    console.error('Registry file ' + REGISTRY_FILE + ' not found.');
    process.exit(1);
  }

  const registry = JSON.parse(fs.readFileSync(REGISTRY_FILE, 'utf-8'));
  const sharedDomain = registry.sharedWorker.domain || 'pragnya.nasven.com';
  const sharedLabels = sharedDomain.split('.');
  const zoneName = sharedLabels.length > 2 ? sharedLabels.slice(1).join('.') : sharedDomain;

  // Deploy-time config is sourced from the control-plane main DB when available
  // (resource IDs persisted by provision-school.mjs), falling back to schools.json.
  const mainDbRegistry = await fetchMainDbRegistry();
  let dbSourced = 0;

  for (const school of registry.schools) {
    if (school.mode !== 'dedicated') continue;

    if (!school.slug || !school.schoolId) {
      console.warn('⚠️ Skipping invalid dedicated school entry (missing slug or schoolId):', school);
      continue;
    }

    const dbRec = mainDbRegistry ? mainDbRegistry.get(school.schoolId) : null;
    const d1DatabaseId = (dbRec && dbRec.d1DatabaseId) || school.d1DatabaseId;
    const r2BucketName = (dbRec && dbRec.r2BucketName) || school.r2BucketName;
    const kvNamespaceId = (dbRec && dbRec.kvNamespaceId) || school.kvNamespaceId;
    const domain = (dbRec && dbRec.domain) || school.domain || (school.slug + '.' + sharedDomain);
    if (dbRec && dbRec.d1DatabaseId) dbSourced++;

    if (!d1DatabaseId) {
      console.warn(
        '⚠️ School ' + school.slug + ' is dedicated but D1 is not provisioned yet. Run "node scripts/provision-school.mjs" first.',
      );
      continue;
    }

    // Refuse anything that is not a strict DNS label before it becomes a Worker
    // name, a route pattern and a filename. A hostile or malformed schools.json
    // (or a poisoned main-DB registry row) must not be able to steer the deploy.
    if (!SLUG_RE.test(String(school.slug))) {
      console.warn('⚠️ Skipping school with an invalid slug (must be a DNS label, a-z 0-9 and -):', school.slug);
      continue;
    }

    const routeDomain = school.slug + '.' + sharedDomain;
    const lines = [
      '# Generated by scripts/generate-school-configs.mjs — do not edit by hand.',
      'name = ' + JSON.stringify(school.slug),
      'main = "./api/index.ts"',
      'compatibility_date = "2026-09-01"',
      'compatibility_flags = ["nodejs_compat"]',
      '',
      '# Route this school\'s subdomain directly to this dedicated worker.',
      '[[routes]]',
      'pattern = ' + JSON.stringify(routeDomain + '/*'),
      'zone_name = ' + JSON.stringify(zoneName),
    ];

    if (domain !== routeDomain && domain.endsWith('.' + zoneName)) {
      lines.push(
        '',
        '[[routes]]',
        'pattern = ' + JSON.stringify(domain + '/*'),
        'zone_name = ' + JSON.stringify(zoneName),
      );
    }

    lines.push(
      '',
      '# Static Flutter web frontend — auto-served like the shared worker.',
      '# SPA fallback serves index.html for client-side routes.',
      '[assets]',
      'directory = "./flutter_apps/school_management_app/build/web"',
      'binding = "ASSETS"',
      'not_found_handling = "single-page-application"',
      '',
      '[vars]',
      'ENVIRONMENT = ' + JSON.stringify(PLATFORM_VARS.ENVIRONMENT),
      'SCHOOL_NAME = ' + JSON.stringify(school.name || PLATFORM_VARS.SCHOOL_NAME),
      'APP_BASE_URL = ' + JSON.stringify('https://' + domain),
      'SCHOOL_ID = ' + JSON.stringify(school.schoolId),
      'SCHOOL_SLUG = ' + JSON.stringify(school.slug),
      'IS_DEDICATED_WORKER = "true"',
      'WEB_PUSH_VAPID_PUBLIC_KEY = ' + JSON.stringify(PLATFORM_VARS.WEB_PUSH_VAPID_PUBLIC_KEY),
      'WEB_PUSH_VAPID_SUBJECT = ' + JSON.stringify(PLATFORM_VARS.WEB_PUSH_VAPID_SUBJECT),
      '',
      '[[d1_databases]]',
      'binding = "DB"',
      'database_name = ' + JSON.stringify('school-management-' + school.slug + '-db'),
      'database_id = ' + JSON.stringify(d1DatabaseId),
      'migrations_dir = "./db_migrations"',
      '',
      '[[r2_buckets]]',
      'binding = "MEDIA_BUCKET"',
      'bucket_name = ' + JSON.stringify(r2BucketName),
      '',
      '[[kv_namespaces]]',
      'binding = "CONFIG_KV"',
      'id = ' + JSON.stringify(kvNamespaceId),
      '',
      // Cloudflare Email binding. Without this on a dedicated worker,
      // api/lib/email.ts short-circuits every send and the school's password
      // reset / invite emails fail SILENTLY — the API reported success while no
      // message was ever delivered. The sending domain must be onboarded in
      // Cloudflare Email Service (see .env.example).
      '[[send_email]]',
      'name = "SEND_EMAIL"',
    );
    const toml = lines.join('\n') + '\n';

    // The filename is derived from registry data. path.join + an explicit
    // containment check keeps a crafted slug from escaping the repo directory
    // (e.g. "../../.github/workflows/evil").
    const outFile = path.join(process.cwd(), 'wrangler-' + school.slug + '.toml');
    const resolvedOut = path.resolve(outFile);
    if (path.dirname(resolvedOut) !== path.resolve(process.cwd())) {
      console.warn('⚠️ Refusing to write config outside the repository root for slug:', school.slug);
      continue;
    }
    fs.writeFileSync(resolvedOut, toml);
    console.log('Generated wrangler-' + school.slug + '.toml (dedicated worker "' + school.slug + '" -> route ' + routeDomain + ')');
  }

  console.log(
    'Finished generating dedicated worker configs.'
    + (mainDbRegistry
      ? ' (' + dbSourced + ' school(s) sourced from main DB registry, rest from schools.json).'
      : ' (sourced from schools.json only).'),
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
